// POGO77 GAMES 共通キャラクター: キャバ嬢(20×20 ドット、右向き。左向きは左右反転で描く)
// 元データ: games/punks-skins-rescue/pogo77_hostess_sprites.js(支給。原本は変更しない)
// 取り込むときに直したところ:
//   - 19 文字の行(目の行 '....YYYSSKSS.......')を 20 文字にそろえた(右に透明を 1 つ足しただけ。見た目は同じ)
//   - hostessRescue の 21 文字の行 2 本の右端の透明を 1 つ削って 20 文字にした(見た目は同じ)
//   - hostessWalk4 の 9・10 行目(首 'YYSs' と 襟 'KPPPK')が入れ替わっていたので、ほかのコマと同じ順に直した
//   - 使っている色(P p Y S s K)はすべて共通パレットにあり、未定義の色はない
// 必要: pixel-sprite.js を先に読み込むこと。
(function () {
  const def = POGO77.chars.def;

  // 頭(9 行)と胴(5 行)はどのコマも同じ
  const HEAD = [
    '.......PPPP.........',
    '......PpPPpP........',
    '.....YYYYYYYY.......',
    '....YYYYYYYYYY......',
    '....YYYSsSSSS.......',
    '....YYYSSKSS........',
    '....YYYSsSSSS.......',
    '.....YYYSSSS........',
    '......YYSs..........',
  ];
  const BODY = [
    '......KPPPK.........',
    '.....SPPPPPSS.......',
    '.....SPpPPpS........',
    '......PPPPP.........',
    '......pPPp..........',
  ];
  const frame = (legs) => def(HEAD.concat(BODY, legs));

  POGO77.chars.register({
    // 立ち姿
    hostessStand: frame([
      '......SS.SS.........',
      '......S...S.........',
      '.....K....K.........',
      '.....P....P.........',
      '.....P.....P........',
      '....PP.....PP.......',
    ]),
    // 歩行 4 コマ
    hostessWalk1: frame([
      '......SS.SS.........',
      '.....SS...S.........',
      '.....S....S.........',
      '....K......K........',
      '....P......P........',
      '...PP.......PP......',
    ]),
    hostessWalk2: frame([
      '......SSSS..........',
      '......S..S..........',
      '.....S....S.........',
      '.....K....K.........',
      '.....P....P.........',
      '....PP....PP........',
    ]),
    hostessWalk3: frame([
      '......SS.SS.........',
      '......S...SS........',
      '......S....S........',
      '.......K....K.......',
      '.......P....P.......',
      '......PP.....PP.....',
    ]),
    hostessWalk4: frame([
      '......SSSS..........',
      '......S..S..........',
      '......S..S..........',
      '......K..K..........',
      '......P..P..........',
      '.....PP..PP.........',
    ]),
    // 救助ポーズ(両手を左右に広げる)
    hostessRescue: def(HEAD.concat([
      '..SS..KPPPK..SS.....',
      '.SS...PPPPPP..SS....',
      '..S...PpPPp...S.....',
      '......PPPPP.........',
      '......pPPp..........',
      '......SS.SS.........',
      '......S...S.........',
      '.....K....K.........',
      '.....P....P.........',
      '.....P.....P........',
      '....PP.....PP.......',
    ])),
  });

  // 歩行のコマ名(順番に再生する)
  POGO77.chars.HOSTESS_WALK = ['hostessWalk1', 'hostessWalk2', 'hostessWalk3', 'hostessWalk4'];
})();
